export default async (p) => {
  await p.viewport(1280, 800);
  await p.goto('skills/stringless/assets/examples/paper-export.html');
  await p.shot('export-rest');
  const s = await p.center('.slot');
  await p.move(s.x, s.y, 8);
  await p.sleep(700);
  const feed = await p.eval(`+getComputedStyle(document.querySelector('.outfeed')).getPropertyValue('--sl-rehearse')`);
  p.expect(feed > 0.9, 'hover feeds the print out of the slot');
  await p.shot('export-rehearse-pdf');
  const csv = await p.center('.stock[data-k="csv"]');
  await p.click(csv.x, csv.y);
  await p.sleep(300);
  p.expect(await p.eval(`document.querySelector('.print').dataset.kind`) === 'csv', 'loading the ledger stock changes the print to CSV');
  p.expect(await p.eval(`document.querySelector('.slot').getAttribute('aria-label')`) === 'Export as CSV', 'the accessible name follows the format');
  await p.move(s.x, s.y, 6);
  await p.sleep(600);
  await p.shot('export-rehearse-csv');
  await p.down(); await p.sleep(40); await p.up();
  await p.sleep(1800);
  p.expect(await p.eval(`[...document.querySelectorAll('.tray a')].map(a => a.download).join()`) === 'q3-sales.csv', 'the print lands in the tray as q3-sales.csv');
  p.expect(await p.eval(`document.querySelector('.tray a').href.startsWith('blob:')`), 'the tray item links to a real file');
  p.expect(await p.eval(`(async () => (await (await fetch(document.querySelector('.tray a').href)).text()).startsWith('Region,Sales'))()`), 'the CSV has the report data');
  p.expect(await p.eval(`(async () => { const t = await pdfBlob().text(); return t.startsWith('%PDF-1.4') && t.trim().endsWith('%%EOF'); })()`), 'the PDF writer produces a complete file');
  await p.move(200, 760, 6);
  await p.sleep(500);
  await p.shot('export-tray');
  await p.viewport(390, 844, true);
  await p.goto('skills/stringless/assets/examples/paper-export.html');
  await p.shot('export-mobile');
};
