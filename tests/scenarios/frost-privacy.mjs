export default async (p) => {
  await p.viewport(1280, 800);
  await p.goto('skills/stringless/assets/examples/frost-privacy.html');
  await p.shot('frost-rest');
  const g = await p.center('.grip');
  await p.move(g.x - 70, g.y + 10, 8);
  await p.sleep(400);
  p.expect(await p.eval(`document.querySelector('.grip').dataset.slState`) === 'near', 'approach wakes the grip');
  await p.move(g.x, g.y, 4);
  await p.sleep(700);
  p.expect(await p.eval(`document.querySelector('.photo').dataset.slPreview`) === 'private', 'hover previews private on the photo');
  await p.shot('frost-rehearse');
  await p.down(); await p.sleep(50); await p.up();
  await p.sleep(900);
  p.expect(await p.eval(`document.querySelector('.photo').hasAttribute('data-private')`), 'click makes it private');
  p.expect(await p.eval(`document.querySelector('.grip').getAttribute('aria-checked')`) === 'true', 'switch state is exposed (aria-checked)');
  const ph = await p.center('.photo');
  await p.move(ph.x - 60, ph.y - 20, 10);
  await p.sleep(700);
  p.expect(await p.eval(`document.querySelector('.pane').style.getPropertyValue('--wr')`) === '78px', 'owner can wipe a clear patch');
  await p.shot('frost-private-wipe');
  await p.move(ph.x, ph.y + 320, 6);
  await p.sleep(700);
  p.expect(await p.eval(`document.querySelector('.pane').style.getPropertyValue('--wr')`) === '0px', 'patch frosts over on leave');
  p.expect(!(await p.eval(`document.querySelector('.photo').dataset.slPreview`)), 'preview clears after leaving');
  await p.shot('frost-private');
  await p.eval(`document.querySelector('.grip').focus()`);
  await p.key(' ', 'Space', { vk: 32, text: ' ' });
  await p.sleep(800);
  p.expect(!(await p.eval(`document.querySelector('.photo').hasAttribute('data-private')`)), 'Space toggles it back to public');
  await p.viewport(390, 844, true);
  await p.goto('skills/stringless/assets/examples/frost-privacy.html');
  await p.shot('frost-mobile');
  const box = await p.center('.grip');
  p.expect(box.w >= 44 && box.h >= 44, `grip hit area is at least 44px (${box.w}x${box.h})`);
};
